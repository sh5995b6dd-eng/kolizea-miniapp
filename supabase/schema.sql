-- KOLIZEA GROUP initial schema for Supabase
-- Run in Supabase Dashboard -> SQL Editor.
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null default '',
  description text not null default '',
  reward numeric(10,2),
  status text not null default 'Новая',
  created_at timestamptz not null default now()
);

alter table public.tasks enable row level security;

-- Public visitors may read active tasks only. No public insert/update/delete.
drop policy if exists "Public can read active tasks" on public.tasks;
create policy "Public can read active tasks"
on public.tasks for select
to anon, authenticated
using (lower(status) not in ('deleted','archived','completed','удалено','архив','завершено'));

revoke insert, update, delete on public.tasks from anon, authenticated;
grant select on public.tasks to anon, authenticated;

